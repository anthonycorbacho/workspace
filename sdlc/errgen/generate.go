package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"
)

// codeTemplate is not formatted: go/format aligns the fields and indents the maps.
var codeTemplate = template.Must(template.New("code").Parse(`// Code generated by errgen from {{.Source}}. DO NOT EDIT.

package {{.Package}}
{{if .UsesFmt}}
import "fmt"
{{end}}
// Error codes.
const (
{{- range .Errors}}
	// {{.Name}}Code is the code of the {{.Name}} error.
	{{.Name}}Code = {{.QuotedCode}}
{{- end}}
)
{{range .Errors}}
// {{.Name}} returns the error {{.Code}} ({{.Kind}}): {{.Message}}.
func {{.Name}}({{.Params}}) *Error {
	return &Error{
		Code: {{.Name}}Code,
		Kind: {{.KindExpr}},
		Message: {{.MessageExpr}},
		Details: {{.Details}},
		internal: {{.Internal}},
	}
}
{{end}}`))

type codeData struct {
	Source  string
	Package string
	UsesFmt bool
	Errors  []constructorData
}

type constructorData struct {
	Name        string
	Code        string
	QuotedCode  string
	Kind        string
	Message     string
	Params      string
	KindExpr    string
	MessageExpr string
	Details     string
	Internal    string
}

// generate returns the formatted Go source of the constructors of a validated catalog.
func generate(c *catalog, pkg string) ([]byte, error) {
	data := codeData{Source: filepath.Base(c.File), Package: pkg}
	for _, e := range c.Errors {
		params := make([]string, 0, len(e.Vars))
		var details, internal []varDef
		for _, v := range e.Vars {
			params = append(params, v.Name+" "+v.Type)
			if v.Internal {
				internal = append(internal, v)
			} else {
				details = append(details, v)
			}
		}
		msg, usesFmt := messageExpr(e.Segments)
		data.UsesFmt = data.UsesFmt || usesFmt
		data.Errors = append(data.Errors, constructorData{
			Name:        e.Name,
			Code:        e.Code,
			QuotedCode:  strconv.Quote(e.Code),
			Kind:        e.Kind,
			Message:     e.Message,
			Params:      strings.Join(params, ", "),
			KindExpr:    kinds[e.Kind],
			MessageExpr: msg,
			Details:     mapLiteral(details),
			Internal:    mapLiteral(internal),
		})
	}

	var buf bytes.Buffer
	if err := codeTemplate.Execute(&buf, data); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		// the catalog is validated, an invalid source is a bug of the generator.
		return nil, fmt.Errorf("format generated code (errgen bug): %w", err)
	}
	return src, nil
}

// messageExpr returns the Go expression of a message and whether it uses fmt.
func messageExpr(segments []segment) (string, bool) {
	var text, layout strings.Builder
	var args []string
	for _, s := range segments {
		if s.placeholder {
			layout.WriteString("%v")
			args = append(args, s.text)
			continue
		}
		text.WriteString(s.text)
		layout.WriteString(strings.ReplaceAll(s.text, "%", "%%"))
	}
	if len(args) == 0 {
		return strconv.Quote(text.String()), false
	}
	return fmt.Sprintf("fmt.Sprintf(%s, %s)", strconv.Quote(layout.String()), strings.Join(args, ", ")), true
}

// mapLiteral returns the details map literal of vars, keyed by the snake_case var names.
func mapLiteral(vars []varDef) string {
	if len(vars) == 0 {
		return "map[string]any{}"
	}
	var b strings.Builder
	b.WriteString("map[string]any{\n")
	for _, v := range vars {
		fmt.Fprintf(&b, "%s: %s,\n", strconv.Quote(snakeCase(v.Name)), v.Name)
	}
	b.WriteString("}")
	return b.String()
}
